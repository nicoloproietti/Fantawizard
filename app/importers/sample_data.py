def load_sample_data(db: Session) -> int:
    existing = db.query(Player).count()
    if existing > 0:
        return 0

    count = 0
    for name, team, role_c, role_m, price, is_pen, seasons in SAMPLE_PLAYERS:
        player = Player(
            name=name,
            team=team,
            role_classic=role_c,
            role_mantra=role_m,
            initial_price=price,
            current_price=price,
            is_penalty_taker=is_pen,
        )
        db.add(player)
        db.flush()

        for s_data in seasons:
            season, app, mins, avg, fanta, gls, ast, pt, ps, pv, yc, rc, og, cs, gc = s_data
            ps_obj = PlayerSeason(
                player_id=player.id,
                season=season,
                appearances=app,
                minutes=mins,
                avg_rating=avg,
                fanta_avg=fanta,
                goals=gls,
                assists=ast,
                penalties_taken=pt,
                penalties_scored=ps,
                penalties_saved=pv,
                yellow_cards=yc,
                red_cards=rc,
                own_goals=og,
                clean_sheets=cs,
                goals_conceded=gc,
            )
            db.add(ps_obj)

        count += 1

    db.commit()
    return count
